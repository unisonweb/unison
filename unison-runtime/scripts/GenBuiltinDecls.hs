-- | The constructor names of a builtin declaration, as the codebase
-- names them, for printing values in a compiled program
ctorNames :: [(R.Reference, [String])]
ctorNames =
  [(R.DerivedId r, map (Text.unpack . Var.name) (DD.constructorVars dd)) | (_, r, dd) <- D.builtinDataDecls]
    ++ [(R.DerivedId r, map (Text.unpack . Var.name) (DD.constructorVars (DD.toDataDecl ed))) | (_, r, ed) <- D.builtinEffectDecls]

showRef :: R.Reference -> String
showRef = \case
  R.Builtin t -> "R.Builtin " ++ show t
  R.DerivedId (R.Id h i) -> "derived " ++ show (Hash.toBase32HexText h) ++ " " ++ show i

main :: IO ()
main =
  writeFile "unison-runtime/src/Unison/Runtime/Builtin/Decls.hs" . unlines $
    [ "-- | Generated by unison-runtime/scripts/GenBuiltinDecls.hs; do not edit.",
      "--",
      "-- The references and constructor numbers of the builtin declarations",
      "-- (Unison.Builtin.Decls) and the order of the builtin types",
      "-- (Unison.Builtin), as constants, so that the runtime needs neither the",
      "-- declarations nor the hashing that makes their references. The test",
      "-- Unison.Test.Runtime.BuiltinDecls checks them against their sources.",
      "module Unison.Runtime.Builtin.Decls where",
      "",
      "import Data.Text (Text)",
      "import Unison.ConstructorReference (GConstructorReference (..))",
      "import Unison.ConstructorType qualified as CT",
      "import Unison.DataDeclaration.ConstructorId (ConstructorId)",
      "import Unison.Hash qualified as Hash",
      "import Unison.Reference (Reference)",
      "import Unison.Reference qualified as R",
      "import Unison.Referent (Referent)",
      "import Unison.Referent qualified as Referent",
      "",
      "derived :: Text -> R.Pos -> Reference",
      "derived h i = R.DerivedId (R.Id (Hash.unsafeFromBase32HexText h) i)",
      ""
    ]
      ++ concat [[n ++ " :: Reference", n ++ " = " ++ showRef r, ""] | (n, r) <- refs]
      ++ concat [[n ++ " :: ConstructorId", n ++ " = " ++ show i, ""] | (n, i) <- ids]
      ++ [ "pairCtorRef, unitCtorRef :: Referent",
           "pairCtorRef = Referent.Con (ConstructorReference pairRef 0) CT.Data",
           "unitCtorRef = Referent.Con (ConstructorReference unitRef 0) CT.Data",
           "",
           "-- | The builtin types, in the order Unison.Builtin.builtinTypes lists them",
           "builtinTypeRefs :: [Reference]",
           "builtinTypeRefs =",
           "  [ " ++ intercalate ",\n    " [showRef r | (_, r) <- B.builtinTypes],
           "  ]",
           "",
           "-- | The builtin data declarations, in order",
           "builtinDataDeclRefs :: [Reference]",
           "builtinDataDeclRefs =",
           "  [ " ++ intercalate ",\n    " [showRef (R.DerivedId r) | (_, r, _) <- D.builtinDataDecls],
           "  ]",
           "",
           "-- | The builtin effect declarations, in order",
           "builtinEffectDeclRefs :: [Reference]",
           "builtinEffectDeclRefs =",
           "  [ " ++ intercalate ",\n    " [showRef (R.DerivedId r) | (_, r, _) <- D.builtinEffectDecls],
           "  ]",
           "",
           "-- | The constructor names of the builtin declarations",
           "builtinConstructorNames :: [(Reference, [Text])]",
           "builtinConstructorNames =",
           "  [ " ++ intercalate ",\n    " ["(" ++ showRef r ++ ", " ++ show ns ++ ")" | (r, ns) <- ctorNames],
           "  ]"
         ]
