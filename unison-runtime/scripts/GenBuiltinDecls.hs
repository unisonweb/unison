-- | Writes src/Unison/Runtime/Builtin/Decls.hs: the references and
-- constructor numbers of the builtin declarations, as constants, so that
-- the runtime does not need the declarations or the hashing that makes
-- their references. Run it from the repository's root after a change to
-- Unison.Builtin.Decls or to the builtin types:
--
--   stack exec -- runghc unison-runtime/scripts/GenBuiltinDecls.hs
--
-- The runtime's test suite checks that the constants agree
-- (Unison.Test.Runtime.BuiltinDecls).
