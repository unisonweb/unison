-- Makes clang's IR for jit_helpers.c and jit_exit.c platform-independent:
-- reads the .ll on stdin, writes the stripped one on stdout. Run through
-- gen-helpers.sh (`stack runghc`), which needs nothing beyond base.
--
-- What goes, and why the result runs on every target the JIT does: the
-- target triple and data layout (the JIT applies the host's); the function
-- attributes that name a CPU, its features, the frame-pointer and
-- stack-protector policy, keeping only the target-neutral ones; the
-- metadata; clang's spelling of the 16-byte return, `[2 x i64]` on arm64
-- against `{ i64, i64 }` on x86-64, normalized to the struct the generator
-- declares; and the alignment of private constant arrays, 16 on x86-64 and
-- 8 on arm64, normalized to 8 (the one difference the Intel runner's check
-- found on 2026-10-18). Clang's output for the same source was compared
-- across arm64 macOS and x86-64 Linux: identical after that normalization,
-- down to the folded closure offsets, which depend only on 64-bit
-- little-endian words. On Windows clang would return the pair through a
-- hidden pointer, a different shape, which is why the committed file is
-- generated on macOS or Linux and used everywhere.
--
-- The layout tables jit_helpers.c reads stay `static` in jit_rt.c's
-- translation unit, because an exported global is addressed through the
-- global offset table, an extra dependent load in every helper that reads
-- one (a few percent on the rope rows), where a private one is a direct
-- address; jit_rt.c lists their names and addresses instead
-- (unison_jit_table_addresses) and startup defines each as an absolute
-- symbol in the JIT before the module is added, as it does the helpers.
module Main (main) where

import Data.Char (isAlphaNum, isDigit)
import Data.List (isPrefixOf, isSuffixOf, stripPrefix)
import System.Environment (getArgs)

-- The arguments are the SHA-256 of the sources and the version line of the
-- clang that compiled them (gen-helpers.sh supplies both), named in the
-- header: the hash so that a change to the C without a regeneration shows
-- in a diff and `--check` can tell the two apart, the clang because the
-- text of its IR depends on its version (LLVM 19 began spelling constant
-- field addresses as byte offsets, `getelementptr i8`, where older ones
-- name the struct and field), so `--check` diffs a regeneration only
-- against the same clang.
main :: IO ()
main = getArgs >>= \args -> interact (strip (arg 0 args) (arg 1 args))
  where
    arg i args = case drop i args of a : _ -> a; [] -> "unknown"

strip :: String -> String -> String -> String
strip sourceHash clangVersion input = header ++ collapse (unlines kept') ++ "\n"
  where
    header =
      "; Generated by gen-helpers.sh from the .c file of the same name. Do not edit.\n"
        ++ "; source sha256: "
        ++ sourceHash
        ++ " (the .c and the headers it includes; gen-helpers.sh --check compares)\n"
        ++ "; clang: "
        ++ clangVersion
        ++ " (the compiler's IR text changes between versions; --check diffs only against this one)\n\n"
    results = map stripLine (lines input)
    kept = [l | (Just l, _) <- results]
    -- attribute groups with nothing left: dropped, with their uses
    empty = [g | (_, Just g) <- results]
    kept' = map (\l -> foldr dropUses l empty) kept

-- | The line as kept (Nothing drops it), and the name of an attribute group
-- that turned out empty (its line is dropped, and so are its uses).
stripLine :: String -> (Maybe String, Maybe String)
stripLine line
  -- the module header: clang's name for the file, the target and its data layout
  | any (`isPrefixOf` line) ["; ModuleID", "source_filename", "target datalayout", "target triple"] = (Nothing, Nothing)
  -- metadata: TBAA, loop hints, the module flags and the compiler's ident
  | "!" `isPrefixOf` line = (Nothing, Nothing)
  | "; Function Attrs:" `isPrefixOf` line = (Nothing, Nothing)
  -- attribute groups: keep the target-neutral attributes and memory(...)
  | Just (group, body) <- attributeGroup line =
      case filter wanted (tokens body) of
        [] -> (Nothing, Just group)
        ks -> (Just ("attributes " ++ group ++ " = { " ++ unwords ks ++ " }"), Nothing)
  | otherwise = (Just (alignment (dropWords (structReturn (dropMetadata line)))), Nothing)
  where
    wanted tok = "memory(" `isPrefixOf` tok || tok `elem` keep
    -- function attributes that mean the same on every target
    keep =
      [ "nounwind",
        "mustprogress",
        "nocallback",
        "nofree",
        "nosync",
        "norecurse",
        "willreturn",
        "inlinehint",
        "noinline",
        "alwaysinline",
        "noreturn",
        "cold"
      ]

-- | @attributes #N = { ... }@, as the group's name and the body between the braces.
attributeGroup :: String -> Maybe (String, String)
attributeGroup line = do
  rest <- stripPrefix "attributes #" line
  let (digits, rest') = span isDigit rest
  body <- stripPrefix " = { " rest'
  if not (null digits) && " }" `isSuffixOf` body
    then Just ('#' : digits, take (length body - 2) body)
    else Nothing

-- | The tokens of an attribute group's body: @memory(...)@, a quoted
-- @"key"@ or @"key"="value"@, or a word with an optional @(...)@.
tokens :: String -> [String]
tokens s = case dropWhile (== ' ') s of
  "" -> []
  s'@('"' : _) ->
    let (tok, rest) = quoted s' in tok : tokens rest
  s' ->
    let (word, rest) = span isWordChar s'
        (tok, rest')
          | ('(' : r) <- rest, (inner, ')' : r') <- break (== ')') r = (word ++ "(" ++ inner ++ ")", r')
          | otherwise = (word, rest)
     in if null word then tokens (drop 1 s') else tok : tokens rest'
  where
    quoted ('"' : r) =
      let (k, r') = break (== '"') r
       in case drop 1 r' of
            '=' : '"' : r'' -> let (v, r''') = break (== '"') r'' in ('"' : k ++ "\"=\"" ++ v ++ "\"", drop 1 r''')
            r'' -> ('"' : k ++ "\"", r'')
    quoted r = ("", r)

isWordChar :: Char -> Bool
isWordChar c = isAlphaNum c || c == '_' || c == '.'

-- | Removes metadata attachments: @, !tbaa !5@, @, !llvm.loop !12@ and the like.
dropMetadata :: String -> String
dropMetadata (',' : ' ' : '!' : r)
  | (name, ' ' : '!' : r') <- span isWordChar r,
    not (null name),
    (num, r'') <- span isDigit r',
    not (null num) =
      dropMetadata r''
dropMetadata (c : r) = c : dropMetadata r
dropMetadata [] = []

-- | The struct return: clang spells the 16-byte pair as an array on arm64
-- and as a struct on x86-64 System V; the generator declares the struct.
structReturn :: String -> String
structReturn s
  | Just r <- stripPrefix "[2 x i64]" s = "{ i64, i64 }" ++ structReturn r
  | c : r <- s = c : structReturn r
  | otherwise = []

-- | Visibility words that only matter to a static linker, each taken with
-- the space after it, where it starts a word.
dropWords :: String -> String
dropWords = go True
  where
    go atStart s
      | atStart, Just r <- matchAny s = go True r
      | c : r <- s = c : go (not (isWordChar c)) r
      | otherwise = []
    matchAny s = foldr (\w acc -> maybe acc Just (stripPrefix (w ++ " ") s)) Nothing ["dso_local", "local_unnamed_addr", "unnamed_addr"]

-- | A private constant's alignment: x86-64 clang aligns arrays of 16 bytes
-- or more to 16, arm64 clang to 8; either is fine for a constant only read
-- by value, so the arm64 spelling is the canonical one.
alignment :: String -> String
alignment line
  | "@" `isPrefixOf` line,
    " private constant " `isInfixOf'` line,
    ", align 16" `isSuffixOf` line =
      take (length line - length ", align 16") line ++ ", align 8"
  | otherwise = line
  where
    isInfixOf' needle hay = any (needle `isPrefixOf`) (suffixes hay)
    suffixes [] = [[]]
    suffixes s@(_ : r) = s : suffixes r

-- | Removes the uses of an emptied attribute group: @ #N@ not followed by
-- another digit.
dropUses :: String -> String -> String
dropUses group = go
  where
    go s
      | Just r <- stripPrefix (' ' : group) s,
        not (startsWithWordChar r) =
          go r
      | c : r <- s = c : go r
      | otherwise = []
    startsWithWordChar (c : _) = isWordChar c
    startsWithWordChar [] = False

-- | Collapses runs of blank lines left by the removals, and trims the ends.
collapse :: String -> String
collapse = dropWhile (== '\n') . reverse . dropWhile (== '\n') . reverse . go
  where
    go ('\n' : '\n' : '\n' : r) = go ('\n' : '\n' : r)
    go (c : r) = c : go r
    go [] = []
